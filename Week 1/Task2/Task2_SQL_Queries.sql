-- Show all records
SELECT * FROM bluestock.sales;

-- Show only Product_ID, Sales_Rep and Sales_Amount columns.
SELECT Product_ID, Sales_Rep, Sales_Amount
FROM sales
;

-- Show all Furniture sales.
SELECT *
FROM sales 
WHERE Product_Category = 'Furniture'
;
-- Show all Online sales.
SELECT *
FROM sales 
WHERE Sales_Channel = 'Online'
;
-- Show all sales greater than ₹5000.
SELECT *
FROM sales 
WHERE Sales_Amount > 5000
;
-- Show Electronics products sold via Retail channel.
SELECT *
FROM sales 
WHERE Product_Category = 'Electronics' and Sales_Channel = 'Online'
;

-- Show transactions from highest sales amount to lowest.
SELECT *
FROM sales
ORDER BY Sales_Amount desc
;
-- Show transactions from lowest discount to highest.
SELECT *
FROM sales
ORDER BY Discount, Quantity_Sold
;

-- How many total transactions exist?
SELECT COUNT(Payment_Method) as Total_Transactions
FROM sales
;
-- What is the total revenue?
SELECT SUM(Sales_Amount) as Revenue
FROM sales
;
-- What is the average sale amount?
SELECT ROUND(AVG(Sales_Amount), 2) as AVG_Sale_Amount
FROM sales
;
-- What is the highest sale amount?
SELECT MAX(Sales_Amount) as MAX_Sale_Amount
FROM sales
;
-- What is the lowest sale amount?
SELECT MIN(Sales_Amount) as MIN_Sale_Amount
FROM sales
;

-- Find total revenue generated by each Sales Rep.
SELECT Sales_Rep, SUM(Sales_Amount) as Revenue_Sales_Rep
FROM sales
GROUP BY Sales_Rep
ORDER BY Revenue_Sales_Rep desc
;
-- Find total revenue generated by each Product Category.
SELECT Product_Category, SUM(Sales_Amount) as Revenue_Per_Product
FROM sales
GROUP BY Product_Category
ORDER BY Revenue_Per_Product desc
;
-- Find total revenue generated by each Sales Channel.
SELECT Sales_Channel, SUM(Sales_Amount) as Revenue_Per_salesChannel
FROM sales
GROUP BY Sales_Channel
ORDER BY Revenue_Per_salesChannel desc
;
-- Find total revenue generated by each Payment Method.
SELECT Payment_Method, SUM(Sales_Amount) as Revenue_PaymentMethod
FROM sales
GROUP BY Payment_Method
ORDER BY Revenue_PaymentMethod desc
;
-- Find average sale amount by Product Category.
SELECT Product_Category, ROUND(AVG(Sales_Amount), 2) as AVG_Sale_Amount
FROM sales
GROUP BY Product_Category
ORDER BY AVG_Sale_Amount desc
;

-- Show categories whose revenue exceeds ₹30,000.
SELECT Product_Category, SUM(Sales_Amount) AS REVENUE_PER_CATEGORY
FROM sales
GROUP BY Product_Category
HAVING REVENUE_PER_CATEGORY > 30000
;
-- Show sales reps whose revenue exceeds ₹20,000.
SELECT Sales_Rep, SUM(Sales_Amount) AS REVENUE_PER_SALES_REP
FROM sales
GROUP BY Sales_Rep
HAVING REVENUE_PER_SALES_REP > 20000
;

-- Find all transactions with sales amount greater than the average sales amount.
WITH cts AS
(
	SELECT AVG(Sales_Amount) AS AVG_SALE_AMOUNT
	FROM sales
)
SELECT *
FROM sales
WHERE Sales_Amount > (SELECT AVG_SALE_AMOUNT FROM cts)
;
-- Find the sales reps whose total revenue is greater than the average revenue of all sales reps.
With cts AS
(
	SELECT AVG(Sales_Amount) as avg_Sales_of_All_Rep
	FROM sales
)
-- Avg revenue of all sales rep
Select Sales_Rep, ROUND(AVG(Sales_Amount), 2) as RevenuePerSalesPerson
FROM sales
GROUP BY Sales_Rep
HAVING RevenuePerSalesPerson > (Select avg_Sales_of_All_Rep FROM cts)
;

-- Rank Sales Reps based on total revenue.
SELECT Sales_Rep, SUM(Sales_Amount), rank() OVER(ORDER BY SUM(Sales_Amount) desc) AS SalesRep_TotalRevenue 
FROM sales
GROUP BY Sales_Rep
;
-- Rank Product Categories based on total revenue.
SELECT Product_Category, SUM(Sales_Amount) AS Total_Revenue, RANK() OVER(ORDER BY SUM(Sales_Amount) desc) as Ranking_System
FROM sales
GROUP BY Product_Category
;
-- Who is the top-performing Sales Rep? One who made highest revenue
SELECT Sales_Rep, SUM(Sales_Amount) as Revenue_by_SalesPerson 
FROM sales
GROUP BY Sales_Rep
ORDER BY Revenue_by_SalesPerson desc
LIMIT 1
;
-- Which Product Category generates the highest revenue?
SELECT Product_Category, SUM(Sales_Amount) as Revenue_by_Category
FROM sales
GROUP BY Product_Category
ORDER BY Revenue_by_Category desc
LIMIT 1
;
-- Which Payment Method contributes the most revenue?
SELECT Payment_Method, SUM(Sales_Amount) as Revenue_by_PaymentMethod
FROM sales
GROUP BY Payment_Method
ORDER BY Revenue_by_PaymentMethod desc
LIMIT 1
;
